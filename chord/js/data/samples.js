// The paper smooths each sample by its photometric-redshift uncertainty
// before scoring (blendFactor = 0.13 x 3 in the reference script), which
// stops a tuning from being rewarded for threading gaps between individual
// sources. Deterministic here (seeded) so a score never wobbles between
// reloads. copies=8 keeps the sandbox responsive; the shape is converged.
export function smoothSample(zs, { blend = 0.39, copies = 8, seed = 42 } = {}) {
  let s = seed >>> 0;
  const rnd = () => { // mulberry32 -> uniform
    s = (s + 0x6D2B79F5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const gauss = () => { // Box-Muller
    const u = Math.max(rnd(), 1e-12), v = rnd();
    return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
  };
  const out = [];
  for (let c = 0; c < copies; c++) {
    for (const z of zs) out.push(Math.max(0.05, z + blend * gauss()));
  }
  return out;
}

